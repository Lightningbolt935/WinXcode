function main() {
  const corpus1Apps = loadHarnessJsonDir(corpus1OutDir);
  const corpus2Apps = loadHarnessJsonDir(corpus2OutDir);

  let targetDate = process.argv.find(a => /^\d{4}-\d{2}-\d{2}$/.test(a));
  if (!targetDate && process.argv.includes("--today")) {
    targetDate = new Date().toISOString().slice(0, 10);
  }

  // Smart date preservation: if no explicit date requested and BASELINE.md exists,
  // check whether regenerating with existing date yields identical document content.
  // If so, preserve existing date to avoid false-positive CI diffs across calendar days.
  if (!targetDate && existsSync(baselineDocPath)) {
    const existingContent = readFileSync(baselineDocPath, "utf-8");
    const m = existingContent.match(/\*\*Generation Date:\*\*\s*([0-9]{4}-[0-9]{2}-[0-9]{2})/);
    if (m) {
      const existingDate = m[1];
      const testContent = renderMarkdown(existingDate, corpus1Apps, corpus2Apps);
      if (testContent.replace(/\r\n/g, "\n") === existingContent.replace(/\r\n/g, "\n")) {
        targetDate = existingDate;
      }
    }
  }

  if (!targetDate) {
    targetDate = new Date().toISOString().slice(0, 10);
  }

  const markdown = renderMarkdown(targetDate, corpus1Apps, corpus2Apps);
  const normalized = markdown.replace(/\r\n/g, "\n");
  writeFileSync(baselineDocPath, normalized, "utf-8");

  const c1Totals = computeTotals(corpus1Apps);
  const c2Totals = computeTotals(corpus2Apps);

  console.log(`[generate-baseline] Successfully generated docs/BASELINE.md (Date: ${targetDate})`);
  console.log(`  Corpus 1 (${corpus1Apps.length} apps): ${c1Totals.CLEAN} CLEAN, ${c1Totals.DEGRADED} DEGRADED, ${c1Totals.EMPTY} EMPTY, ${c1Totals.FAILED} FAILED`);
  console.log(`  Corpus 2 (${corpus2Apps.length} apps): ${c2Totals.CLEAN} CLEAN, ${c2Totals.DEGRADED} DEGRADED, ${c2Totals.EMPTY} EMPTY, ${c2Totals.FAILED} FAILED`);
}

main();
